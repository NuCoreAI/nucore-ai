@pytest.mark.asyncio
async def test_second_call_overwrites_and_never_includes_its_own_dist(tmp_path):
    plugin_dir = _write_full_plugin_dir(tmp_path)
    backend = FakeBackend()

    await package_generated_plugin(
        backend, {"location": "acme_pool"}, plugin_output_root=str(tmp_path), secret_values=[]
    )

    (plugin_dir / "extra_helper.py").write_text("def helper():\n    return 2\n")
    result = await package_generated_plugin(
        backend, {"location": "acme_pool"}, plugin_output_root=str(tmp_path), secret_values=[]
    )

    archive_path = plugin_dir / "dist" / "Acme-Pool-1.2.3.tar.gz"
    with tarfile.open(archive_path) as tar:
        names = tar.getnames()
        extracted = tar.extractfile("extra_helper.py").read().decode()

    assert "return 2" in extracted
    assert not any(n.startswith("dist/") for n in names)
    assert len(names) == len(set(names))


@pytest.mark.asyncio
async def test_permissions_refresh_and_notify_errors_are_non_fatal(tmp_path):
    _write_full_plugin_dir(tmp_path)

    class _FailingBackend(FakeBackend):
        async def refresh_eisy_ai_permissions(self):
            return {"error": "permissions boom"}

        async def notify_plugin_files_changed(self, paths):
            return {"error": "notify boom"}

    result = await package_generated_plugin(
        _FailingBackend(), {"location": "acme_pool"}, plugin_output_root=str(tmp_path), secret_values=[]
    )

    assert result["permissions_refresh_error"] == "permissions boom"
    assert result["files_changed_notify_error"] == "notify boom"
    assert (tmp_path / "acme_pool" / "dist" / "Acme-Pool-1.2.3.tar.gz").is_file()
