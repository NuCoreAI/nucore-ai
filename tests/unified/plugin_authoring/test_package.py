@pytest.mark.asyncio
async def test_happy_path_includes_expected_files_excludes_the_rest(tmp_path):
    _write_full_plugin_dir(tmp_path)
    backend = FakeBackend()

    result = await package_generated_plugin(
        backend, {"location": "acme_pool"}, plugin_output_root=str(tmp_path), secret_values=[]
    )

    assert result["location"] == "acme_pool"
    assert result["plugin_name"] == "Acme-Pool"
    assert result["version"] == "1.2.3"
    archive_path = tmp_path / "acme_pool" / "dist" / "Acme-Pool-1.2.3.tar.gz"
    assert result["archive_path"] == str(archive_path)
    assert archive_path.is_file()

    with tarfile.open(archive_path) as tar:
        names = set(tar.getnames())

    expected = {
        "profile.json",
        "plugin.py",
        "main.py",
        "version.py",
        "README.md",
        "LICENSE.md",
        "requirements.txt",
        "install.sh",
        "SomeNode.py",
        "POLYGLOT_CONFIG.md",
        "extra_helper.py",
    }
    assert names == expected
    # no top-level directory
    assert all("/" not in n for n in names)

    excluded = {
        "server_entry.json",
        "generation_inputs.json",
        "context.md",
        "sources.md",
        ".iox_env",
        ".vscode/launch.json",
        ".git/HEAD",
        "__pycache__/plugin.cpython-312.pyc",
        "tests/test_plugin.py",
        "persist/session.json",
        "data/upload.bin",
    }
    assert names.isdisjoint(excluded)


@pytest.mark.asyncio
async def test_secret_in_file_content_refuses_to_write_archive(tmp_path):
    _write_full_plugin_dir(tmp_path)
    (tmp_path / "acme_pool" / "extra_helper.py").write_text("API_KEY = 'super-secret-value'\n")
    backend = FakeBackend()

    result = await package_generated_plugin(
        backend, {"location": "acme_pool"}, plugin_output_root=str(tmp_path),
        secret_values=["super-secret-value"],
    )

    assert "error" in result
    dist_dir = tmp_path / "acme_pool" / "dist"
    assert not dist_dir.exists() or not any(dist_dir.iterdir())


