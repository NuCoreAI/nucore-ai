"""package_generated_plugin -- builds dist/<plugin-name>-<version>.tar.gz for a
generated plugin. Denylist-based (walks the whole plugin directory, excludes
a known-bad set), not an allowlist tied to generation_inputs.json, so a
hand-added extra file is still included. See handlers/package.py's own
docstring for the full exclusion rationale.
"""

from __future__ import annotations

import json
import tarfile

import pytest

from unified.plugin_authoring.handlers.package import package_generated_plugin


class FakeBackend:
    async def refresh_eisy_ai_permissions(self):
        return {"successful": True}

    async def notify_plugin_files_changed(self, paths):
        return {"successful": True}


def _write_full_plugin_dir(tmp_path, *, name="Acme Pool", version="1.2.3", generation_inputs_version="9.9.9"):
    plugin_dir = tmp_path / "acme_pool"
    plugin_dir.mkdir(parents=True)

    (plugin_dir / "profile.json").write_text(json.dumps({"nodedefs": []}))
    (plugin_dir / "plugin.py").write_text("class Controller:\n    pass\n")
    (plugin_dir / "main.py").write_text("print('main')\n")
    (plugin_dir / "version.py").write_text(
        f'"""Generated by plugin_authoring. Bump on every regeneration."""\n\nud_plugin_version = "{version}"\n'
    )
    (plugin_dir / "server_entry.json").write_text(json.dumps({"name": name, "nsid": "local.acme_pool"}))
    (plugin_dir / "README.md").write_text("# Acme Pool\n")
    (plugin_dir / "LICENSE.md").write_text("MIT\n")
    (plugin_dir / "requirements.txt").write_text("udi_interface\n")
    (plugin_dir / "install.sh").write_text("#!/bin/sh\necho install\n")
    (plugin_dir / "generation_inputs.json").write_text(json.dumps({"version": generation_inputs_version}))
    (plugin_dir / "SomeNode.py").write_text("class SomeNode:\n    pass\n")
    (plugin_dir / "POLYGLOT_CONFIG.md").write_text("Config docs\n")
    (plugin_dir / "extra_helper.py").write_text("def helper():\n    return 1\n")
    (plugin_dir / "context.md").write_text("iteration log\n")
    (plugin_dir / "sources.md").write_text("sources\n")

    (plugin_dir / ".iox_env").write_text("PG3INIT=secrettoken\n")
    vscode_dir = plugin_dir / ".vscode"
    vscode_dir.mkdir()
    (vscode_dir / "launch.json").write_text("{}\n")

    git_dir = plugin_dir / ".git"
    git_dir.mkdir()
    (git_dir / "HEAD").write_text("ref: refs/heads/main\n")

    pycache_dir = plugin_dir / "__pycache__"
    pycache_dir.mkdir()
    (pycache_dir / "plugin.cpython-312.pyc").write_bytes(b"\x00\x01")

    tests_dir = plugin_dir / "tests"
    tests_dir.mkdir()
    (tests_dir / "test_plugin.py").write_text("def test_x():\n    pass\n")

    persist_dir = plugin_dir / "persist"
    persist_dir.mkdir()
    (persist_dir / "session.json").write_text("{}\n")

    data_dir = plugin_dir / "data"
    data_dir.mkdir()
    (data_dir / "upload.bin").write_bytes(b"\x00")

    return plugin_dir


